#!/usr/bin/env python3
"""Export design.json tokens to CSS variables, a Tailwind theme, and a flat JSON map."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

try:
    from validate_design_system import (
        get_node,
        is_alias,
        iter_tokens,
        resolve_value,
        token_root_for_theme,
    )
except ImportError:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from validate_design_system import (  # type: ignore[no-redef]
        get_node,
        is_alias,
        iter_tokens,
        resolve_value,
        token_root_for_theme,
    )

LAYERS = ("primitive", "semantic", "component")


def dotted(path: tuple[str, ...]) -> str:
    return ".".join(path)


def slug(value: str) -> str:
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", value)
    value = re.sub(r"[^A-Za-z0-9]+", "-", value).strip("-").lower()
    return value or "token"


def css_name(path: tuple[str, ...], prefix: str = "--ds-") -> str:
    return prefix + "-".join(slug(part) for part in path)


def alias_target(value: Any) -> tuple[str, ...] | None:
    if not is_alias(value):
        return None
    return tuple(part for part in value.strip()[1:-1].split(".") if part)


def resolve_deep(value: Any, root: dict[str, Any]) -> Any:
    if is_alias(value):
        return resolve_value(value, root)
    if isinstance(value, dict):
        if "$value" in value:
            return resolve_deep(value["$value"], root)
        return {key: resolve_deep(item, root) for key, item in value.items()}
    if isinstance(value, list):
        return [resolve_deep(item, root) for item in value]
    return value


def shadow_css(value: dict[str, Any]) -> str:
    return " ".join(
        str(value.get(key, "0")) for key in ("offsetX", "offsetY", "blur", "spread")
    ) + " " + str(value.get("color", "currentColor"))


def typography_css(value: dict[str, Any], root: dict[str, Any]) -> str:
    def resolved(key: str, fallback: str = "") -> Any:
        item = value.get(key, fallback)
        return resolve_value(item, root) if is_alias(item) else item

    weight = resolved("fontWeight", "400")
    size = resolved("fontSize", "16px")
    line_height = resolved("lineHeight", "normal")
    family = resolved("fontFamily", "inherit")
    return f"{weight} {size}/{line_height} {family}"


def css_value(value: Any, root: dict[str, Any], prefix: str) -> str:
    target = alias_target(value)
    if target is not None:
        return f"var({css_name(target, prefix)})"
    if isinstance(value, dict):
        if "$value" in value:
            return css_value(value["$value"], root, prefix)
        if all(key in value for key in ("offsetX", "offsetY", "blur", "spread")):
            return shadow_css(value)
        if "fontFamily" in value or "fontSize" in value:
            return typography_css(value, root)
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return str(value)


def all_tokens(data: dict[str, Any]) -> list[tuple[tuple[str, ...], Any, str | None]]:
    tokens: list[tuple[tuple[str, ...], Any, str | None]] = []
    for layer in LAYERS:
        node = data.get(layer, {})
        if isinstance(node, dict):
            tokens.extend(iter_tokens(node, (layer,)))
    return tokens


def render_css(data: dict[str, Any], prefix: str) -> str:
    base_root = token_root_for_theme(data, "light")
    lines = [
        "/* Generated by export_tokens.py from design.json. Do not edit by hand. */",
        ":root {",
    ]
    seen: set[str] = set()
    for path, value, _token_type in all_tokens(data):
        name = css_name(path, prefix)
        if name in seen:
            raise SystemExit(f"CSS variable collision for {dotted(path)}: {name}")
        seen.add(name)
        lines.append(f"  {name}: {css_value(value, base_root, prefix)};")
    lines.append("}")

    themes = data.get("themes", {})
    if isinstance(themes, dict) and isinstance(themes.get("dark"), dict):
        dark_root = token_root_for_theme(data, "dark")
        base_semantic = base_root.get("semantic", {})
        dark_semantic = dark_root.get("semantic", {})
        overrides: list[str] = []
        for path, value, _token_type in iter_tokens(dark_semantic, ("semantic",)):
            base_node = get_node(base_semantic, path[1:])
            base_value = resolve_deep(base_node, base_root) if base_node is not None else None
            dark_value = resolve_deep(value, dark_root)
            if base_value != dark_value:
                overrides.append(f"  {css_name(path, prefix)}: {css_value(value, dark_root, prefix)};")
        if overrides:
            lines.append("")
            lines.append('[data-theme="dark"] {')
            lines.extend(overrides)
            lines.append("}")
            lines.append("")
            lines.append("@media (prefers-color-scheme: dark) {")
            lines.append('  :root:not([data-theme]) {')
            lines.extend("  " + line for line in overrides)
            lines.append("  }")
            lines.append("}")
    return "\n".join(lines) + "\n"


def set_nested(tree: dict[str, Any], path: tuple[str, ...], value: Any) -> None:
    node = tree
    for key in path[:-1]:
        child = node.get(key)
        if not isinstance(child, dict):
            child = {}
            node[key] = child
        node = child
    node[path[-1]] = value


def tailwind_theme(data: dict[str, Any]) -> dict[str, Any]:
    root = token_root_for_theme(data, "light")
    semantic = data.get("semantic", {})
    if not isinstance(semantic, dict):
        return {}

    theme: dict[str, Any] = {}
    for path, value, token_type in iter_tokens(semantic):
        resolved = resolve_deep(value, root)
        category = path[0] if path else ""
        rest = path[1:]
        if not rest:
            continue
        if category == "color":
            set_nested(theme.setdefault("colors", {}), rest, resolved)
        elif category == "spacing":
            set_nested(theme.setdefault("spacing", {}), rest, resolved)
        elif category == "radius":
            set_nested(theme.setdefault("borderRadius", {}), rest, resolved)
        elif category == "elevation":
            if isinstance(resolved, dict):
                resolved = shadow_css(resolved)
            set_nested(theme.setdefault("boxShadow", {}), rest, resolved)
        elif category == "typography" and isinstance(resolved, dict):
            entry: list[Any] = [resolved.get("fontSize", "16px")]
            options = {
                key: resolved[key]
                for key in ("lineHeight", "letterSpacing", "fontWeight", "fontFamily")
                if key in resolved
            }
            if options:
                entry.append(options)
            set_nested(theme.setdefault("fontSize", {}), ("-".join(rest),), entry)
        elif category == "motion" and rest[0] == "duration":
            set_nested(theme.setdefault("transitionDuration", {}), rest[1:], resolved)
        elif category == "motion" and rest[0] == "easing":
            set_nested(theme.setdefault("transitionTimingFunction", {}), rest[1:], resolved)
        elif category == "layout" and rest:
            group = rest[0]
            if group == "breakpoint":
                set_nested(theme.setdefault("screens", {}), rest[1:], resolved)
            elif group == "container":
                set_nested(theme.setdefault("maxWidth", {}), rest[1:], resolved)
            elif group == "grid" and len(rest) >= 3:
                grid_group = rest[1]
                if grid_group == "columns":
                    set_nested(
                        theme.setdefault("gridTemplateColumns", {}),
                        rest[2:],
                        f"repeat({resolved}, minmax(0, 1fr))",
                    )
                elif grid_group == "gutter":
                    set_nested(theme.setdefault("gap", {}), rest[2:], resolved)
                elif grid_group == "margin":
                    set_nested(theme.setdefault("padding", {}), rest[2:], resolved)
        elif token_type == "color":
            set_nested(theme.setdefault("colors", {}), path, resolved)
    return theme


def flat_tokens(data: dict[str, Any]) -> dict[str, Any]:
    root = token_root_for_theme(data, "light")
    tokens = {
        dotted(path): resolve_deep(value, root)
        for path, value, _token_type in all_tokens(data)
    }
    themes: dict[str, Any] = {}
    raw_themes = data.get("themes", {})
    if isinstance(raw_themes, dict):
        for name, theme in raw_themes.items():
            if not isinstance(theme, dict):
                continue
            theme_root = token_root_for_theme(data, name)
            themes[name] = {
                dotted(path): resolve_deep(value, theme_root)
                for path, value, _token_type in iter_tokens(
                    theme_root.get("semantic", {}), ("semantic",)
                )
            }
    return {"meta": data.get("meta", {}), "tokens": tokens, "themes": themes}


def write_json(path: Path, payload: Any) -> None:
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def export(data: dict[str, Any], out_dir: Path, formats: set[str], prefix: str) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    if "css" in formats:
        css_path = out_dir / "tokens.css"
        css_path.write_text(render_css(data, prefix), encoding="utf-8")
        written.append(css_path)

    if "tailwind" in formats:
        theme = tailwind_theme(data)
        json_path = out_dir / "tailwind.tokens.json"
        write_json(json_path, theme)
        written.append(json_path)

        js_path = out_dir / "tailwind.tokens.js"
        js_path.write_text(
            "/** @type {import('tailwindcss').Config} */\n"
            "module.exports = {\n"
            "  theme: {\n"
            f"    extend: {json.dumps(theme, indent=6, ensure_ascii=False)},\n"
            "  },\n"
            "};\n",
            encoding="utf-8",
        )
        written.append(js_path)

    if "json" in formats:
        json_path = out_dir / "tokens.flat.json"
        write_json(json_path, flat_tokens(data))
        written.append(json_path)

    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export design.json tokens.")
    parser.add_argument("--tokens", type=Path, required=True, help="Path to design.json")
    parser.add_argument("--out", type=Path, default=Path("dist"), help="Output directory (default: dist)")
    parser.add_argument(
        "--format",
        choices=("css", "tailwind", "json", "all"),
        default="all",
        help="Output format (default: all)",
    )
    parser.add_argument("--prefix", default="--ds-", help="CSS custom property prefix (default: --ds-)")
    args = parser.parse_args(argv)

    if not args.tokens.exists():
        print(f"Token file not found: {args.tokens}", file=sys.stderr)
        return 1
    try:
        data = json.loads(args.tokens.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        print(f"Invalid JSON in {args.tokens}: {error}", file=sys.stderr)
        return 1
    if not isinstance(data, dict):
        print("design.json must contain a JSON object.", file=sys.stderr)
        return 1

    prefix = args.prefix if args.prefix.startswith("--") else f"--{args.prefix}"
    formats = {"css", "tailwind", "json"} if args.format == "all" else {args.format}
    try:
        written = export(data, args.out, formats, prefix)
    except (KeyError, ValueError) as error:
        print(f"Token export failed: {error}", file=sys.stderr)
        return 1

    print(f"Exported {len(written)} file(s) to {args.out}:")
    for path in written:
        print(f"  - {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
